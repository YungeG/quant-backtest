def test_request_rejects_wrong_identity_date_hash_and_forged_fields() -> None:
    archive, checksum = evidence()
    with pytest.raises(ValueError, match="exact KORU"):
        request_for(
            archive,
            checksum,
            instrument_id=InstrumentId(
                VenueId("binance_usdm"), "btc-usdt-perpetual"
            ),
        )
    with pytest.raises(ValueError, match="on or after"):
        request_for(archive, checksum, utc_date="2026-07-14")
    with pytest.raises(ValueError, match="ISO UTC date"):
        request_for(archive, checksum, utc_date="2026-7-16")
    with pytest.raises(ValueError, match="canonical sha256"):
        BinanceUsdmKoruAggregateTradesSourceBoundedRequestV1(
            InstrumentId(
                VenueId("binance_usdm"), "koru-usdt-tradifi-perpetual"
            ),
            UTC_DATE,
            ARCHIVE_AVAILABLE_AT,
            ACQUIRED_AT,
            "sha256:not-a-hash",
            sha256(checksum),
        )

