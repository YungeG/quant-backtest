def sha256(value: bytes) -> str:
    return "sha256:" + hashlib.sha256(value).hexdigest()


def archive_bytes(
    rows: tuple[tuple[str, ...], ...] = ROWS,
    *,
    member_name: str = f"KORUUSDT-aggTrades-{UTC_DATE}.csv",
) -> bytes:
    csv_bytes = b"".join((",".join(row) + "\n").encode() for row in rows)
    output = io.BytesIO()
    info = ZipInfo(member_name, (2026, 7, 16, 0, 0, 0))
    info.compress_type = ZIP_STORED
    info.external_attr = 0o644 << 16
    with ZipFile(output, "w") as archive:
        archive.writestr(info, csv_bytes)
    return output.getvalue()


def evidence(
    rows: tuple[tuple[str, ...], ...] = ROWS,
    *,
    member_name: str = f"KORUUSDT-aggTrades-{UTC_DATE}.csv",
    checksum_name: str = f"KORUUSDT-aggTrades-{UTC_DATE}.zip",
    checksum_separator: str = "  ",
) -> tuple[bytes, bytes]:
    archive = archive_bytes(rows, member_name=member_name)
    checksum = (
        sha256(archive)[7:] + checksum_separator + checksum_name + "\n"
    ).encode()
    return archive, checksum


def request_for(
    archive: bytes,
    checksum: bytes,
    *,
    instrument_id: InstrumentId | None = None,
    utc_date: str = UTC_DATE,
    archive_available_at: int = ARCHIVE_AVAILABLE_AT,
    acquired_at: int = ACQUIRED_AT,
    expected_archive_sha256: str | None = None,
) -> BinanceUsdmKoruAggregateTradesSourceBoundedRequestV1:
    return BinanceUsdmKoruAggregateTradesSourceBoundedRequestV1(
        instrument_id
        or InstrumentId(VenueId("binance_usdm"), "koru-usdt-tradifi-perpetual"),
        utc_date,
        archive_available_at,
        acquired_at,
        expected_archive_sha256 or sha256(archive),
        sha256(checksum),
    )


class Fetch:
    def __init__(self, responses: dict[str, list[tuple[int, bytes] | Exception]]) -> None:
        self.responses = responses
        self.calls: list[str] = []

    def __call__(self, url: str) -> tuple[int, bytes]:
        self.calls.append(url)
        response = self.responses[url].pop(0)
        if isinstance(response, Exception):
            raise response
        return response


def capture(
    rows: tuple[tuple[str, ...], ...] = ROWS,
    *,
    member_name: str = f"KORUUSDT-aggTrades-{UTC_DATE}.csv",
    archive_available_at: int = ARCHIVE_AVAILABLE_AT,
) -> BinanceUsdmKoruAggregateTradesSourceBoundedCaptureResultV1:
    archive, checksum = evidence(rows, member_name=member_name)
    request = request_for(
        archive, checksum, archive_available_at=archive_available_at
    )
    archive_url, checksum_url = request.urls
    outcome = capture_binance_usdm_koru_aggregate_trades_source_bounded_v1(
        request,
        Fetch({archive_url: [(200, archive)], checksum_url: [(200, checksum)]}),
    )
    assert outcome.failure is None
    assert outcome.result is not None
    return outcome.result


